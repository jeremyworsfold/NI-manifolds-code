# Gaussian (LNA) smoothing of a stationary PDMP density at finite population V = 1/μ.

"""Gap kept between the quadrature domain and the PDMP support endpoints, where the
branch densities have integrable power-law singularities."""
const INSET = 5e-15

"""
    finite_size_profile(s::StationaryPDMP, population; grid = nothing, points = 500)
        -> (; grid, plus, minus, total)

Branch densities of the PDMP law `s` convolved with the LNA kernel at finite population
V = `population` (μ = 1/V), on `grid`, normalised together by the trapezoidal rule. By default
the grid spans the support, widened by four LNA standard deviations `4/√V`, with `points` points.
"""
function finite_size_profile(
    s::StationaryPDMP, population::Integer; grid=nothing, points::Integer=500
)
    population > 0 || throw(ArgumentError("population must be positive"))
    x = if isnothing(grid)
        lo, hi = support(s)
        collect(range(lo - 4 / sqrt(population), hi + 4 / sqrt(population); length=points))
    else
        collect(grid)
    end
    μ = 1 / population
    plus = [LNA_convolution(s, :plus, xi, μ) for xi in x]
    minus = [LNA_convolution(s, :minus, xi, μ) for xi in x]
    total = solve(SampledIntegralProblem(plus .+ minus, x), TrapezoidalRule()).u
    plus, minus = plus ./ total, minus ./ total
    return (; grid=x, plus, minus, total=plus .+ minus)
end

"""
    density_l1(s::StationaryPDMP, masses, population) -> Float64

L1 distance on the lattice `s = n/V` between exact masses of `n = 0, 1, …` (as from
`population_masses`) and the LNA-smoothed density of `s` at volume V = `population`, the
L1 distance between exact TK2 masses and the finite-size PDMP profile.
"""
function density_l1(s::StationaryPDMP, masses::AbstractVector, population::Integer)
    grid = (0:(length(masses) - 1)) ./ population
    theory = finite_size_profile(s, population; grid).total ./ population
    return sum(abs, masses .- theory)
end

"""
    density_w1(s::StationaryPDMP, masses, population) -> Float64

Wasserstein-1 distance ∫|F - F_exact| ds on the lattice `s = n/V` between the exact masses and
the LNA-smoothed PDMP masses of [`density_l1`](@ref). The manuscript's error panels use it, as
for the ant model, because it weights a misplaced mass by how far it is moved.
"""
function density_w1(s::StationaryPDMP, masses::AbstractVector, population::Integer)
    grid = (0:(length(masses) - 1)) ./ population
    theory = finite_size_profile(s, population; grid).total ./ population
    return sum(abs, cumsum(masses) .- cumsum(theory)) / population
end

"""
    LNA_fluctuation(ξ, ϕ)

Gaussian fluctuation kernel with variance `ϕ` in `ξ` units (i.e. `μϕ` in `s`, `μ = 1/V`). This is the
attracting conditional variance for the leading branch flow: if
`dϕ/dt = 1-k_i*ϕ`, then `dv/dt = -2k_i*v+1+k_i*ϕ` implies `v=ϕ` on either branch. It is also
exact at each uncorrected branch fixed point, where the local immigration--death process is
Poisson.

This does not imply that the kernel has no mixed `εμ` correction. Repeating the conditional
LNA about the corrected flow `dϕ/dt = 1-k_i*ϕ+ε*d_i`, while retaining the leading demographic
noise, gives `v_i(ϕ)=ϕ-ε*d_i/(2k_i)`. This corrected-flow closure is only a partial mixed-order
correction, not the complete branch-coupled `O(εμ)` operator generated by the excursion reduction.
"""
LNA_fluctuation(ξ, ϕ) = exp(-ξ^2 / (2ϕ)) / sqrt(2π * ϕ)

"""`∫ N(ξ; 0, ϕ) Π_branch(ϕ) dϕ` with `ξ = (x - ϕ)/√μ`, by adaptive quadrature over the support."""
function LNA_convolution(s::StationaryPDMP, branch::Symbol, x::Real, μ::Real)
    lo, hi = support(s)
    integrand(ϕ, _) = LNA_fluctuation((x - ϕ) / sqrt(μ), ϕ) * branch_density(s, ϕ, branch)
    return solve(IntegralProblem(integrand, (lo + INSET, hi - INSET)), QuadGKJL()).u
end
